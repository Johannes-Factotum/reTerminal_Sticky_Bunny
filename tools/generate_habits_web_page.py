#!/usr/bin/env python3
"""Embed assets/habits/web/index.html (with bunny art as data URIs) into
src/apps/habits/habits_web_page.cpp for the phone editor."""

from __future__ import annotations

import base64
import io
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
PAGE = ROOT / "assets" / "habits" / "web" / "index.html"
ART = ROOT / "assets" / "habits" / "firmware"
OUT = ROOT / "src" / "apps" / "habits" / "habits_web_page.cpp"
# Order matches HabitIcon in src/apps/habits/habits_model.h.
ICONS = ("generic", "sun_salutation", "pullups", "breakfast", "morning_pages")


def data_uri(name: str) -> str:
    image = Image.open(ART / f"{name}.png").convert("1")
    buffer = io.BytesIO()
    image.save(buffer, format="PNG", optimize=True)
    return "data:image/png;base64," + base64.b64encode(buffer.getvalue()).decode()


def main() -> None:
    html = PAGE.read_text(encoding="utf-8")
    uris = ",".join(f'"{data_uri(name)}"' for name in ICONS)
    html = html.replace("<script>\n",
                        f"<script>window.HABIT_ART=[{uris}];</script>\n<script>\n",
                        1)
    assert ')HTML"' not in html
    OUT.write_text(
        "// Generated by tools/generate_habits_web_page.py - do not edit.\n"
        '#include "habits_web.h"\n\n'
        f'extern const char kHabitsWebPage[] = R"HTML({html})HTML";\n',
        encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(html)} bytes of HTML)")


if __name__ == "__main__":
    main()
