#!/usr/bin/env python3
"""Pack assets/flashcards/decks/*.tsv into src/apps/flashcards/flashcards_deck_data.cpp.

Deck file format (UTF-8, also accepts Anki "Notes in Plain Text" exports):
  #deck:Display Name          optional, defaults to the file name
  # any other line starting with '#' is a comment
  front<TAB>back              one card per line; extra columns are ignored

Basic HTML from Anki exports (<br>, <b>, &nbsp; ...) is stripped.
Decks are sorted by file name; that order fixes each deck's storage slot.
"""

from __future__ import annotations

import html
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DECK_DIR = ROOT / "assets" / "flashcards" / "decks"
OUTPUT = ROOT / "src" / "apps" / "flashcards" / "flashcards_deck_data.cpp"
MAX_CARDS = 16000
MAX_FIELD_BYTES = 240
MAX_NAME_BYTES = 28


def clean(text: str) -> str:
    text = re.sub(r"<br\s*/?>", " / ", text, flags=re.IGNORECASE)
    text = re.sub(r"<[^>]+>", "", text)
    text = html.unescape(text).replace(" ", " ")
    text = re.sub(r"\s+", " ", text).strip()
    encoded = text.encode("utf-8")
    if len(encoded) > MAX_FIELD_BYTES:
        text = encoded[:MAX_FIELD_BYTES].decode("utf-8", "ignore") + "..."
    return text


def c_literal(text: str) -> str:
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '\\0"'


def load_deck(path: Path) -> tuple[str, list[tuple[str, str]]]:
    name = path.stem.replace("_", " ").title()
    cards: list[tuple[str, str]] = []
    for line in path.read_text(encoding="utf-8-sig").splitlines():
        if line.startswith("#deck:"):
            name = line[6:].strip()
            continue
        if not line.strip() or line.startswith("#"):
            continue
        fields = line.split("\t")
        if len(fields) < 2:
            continue
        front, back = clean(fields[0]), clean(fields[1])
        if front and back:
            cards.append((front, back))
    if len(cards) > MAX_CARDS:
        print(f"warning: {path.name} truncated to {MAX_CARDS} cards",
              file=sys.stderr)
        cards = cards[:MAX_CARDS]
    name = name.encode("utf-8")[:MAX_NAME_BYTES].decode("utf-8", "ignore")
    return name, cards


def main() -> None:
    paths = sorted(DECK_DIR.glob("*.tsv")) + sorted(DECK_DIR.glob("*.txt"))
    if not paths:
        raise SystemExit(f"no decks found in {DECK_DIR}")
    out = [
        "// Generated by tools/generate_flashcards_decks.py - do not edit.\n",
        '#include "flashcards_deck.h"\n\n',
        "namespace {\n\n",
    ]
    deck_entries = []
    for index, path in enumerate(paths):
        name, cards = load_deck(path)
        offsets = []
        position = 0
        out.append(f"// {path.name}: {len(cards)} cards\n")
        out.append(f"const char kDeck{index}Blob[] =\n")
        for front, back in cards:
            offsets.append(position)
            position += len(front.encode("utf-8")) + 1
            offsets.append(position)
            position += len(back.encode("utf-8")) + 1
            out.append(f"    {c_literal(front)} {c_literal(back)}\n")
        out.append("    ;\n\n")
        out.append(f"const uint32_t kDeck{index}Offsets[] = {{\n")
        for start in range(0, len(offsets), 12):
            chunk = ", ".join(f"{v}U" for v in offsets[start:start + 12])
            out.append(f"    {chunk},\n")
        out.append("};\n\n")
        deck_entries.append(
            f"    {{{c_literal(name)[:-3]}\", {len(cards)}U, "
            f"kDeck{index}Blob, kDeck{index}Offsets}},\n")
        print(f"{path.name}: '{name}' {len(cards)} cards")
    out.append("const FlashcardsDeck kDecks[] = {\n")
    out.extend(deck_entries)
    out.append("};\n\n}  // namespace\n\n")
    out.append("size_t flashcards_deck_count()\n{\n"
               "    return sizeof(kDecks) / sizeof(kDecks[0]);\n}\n\n")
    out.append("const FlashcardsDeck &flashcards_deck(size_t index)\n{\n"
               "    return kDecks[index < flashcards_deck_count() ? index : 0U];"
               "\n}\n")
    OUTPUT.write_text("".join(out), encoding="utf-8")


if __name__ == "__main__":
    main()
